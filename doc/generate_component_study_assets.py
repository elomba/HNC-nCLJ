#!/usr/bin/env python3
"""Generate manuscript tables/plots from the completed, immutable MD summaries."""
from pathlib import Path
import json
import shutil
import numpy as np
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt

DOC=Path(__file__).resolve().parent
ROOT=DOC.parent/'ComponentEntropyStudy_20261030'
PAIR=DOC.parent/'MDPairEntropyAssessment'/'results'/'summary.json'
OUT=DOC/'figures'
S=json.loads((ROOT/'results/summary.json').read_text())
G=json.loads((ROOT/'results/diagnostics.json').read_text())
P=json.loads(PAIR.read_text())
assert S['complete'] and S['completed_replicas']==24
ORDER=[('B3','baseline_3C'),('B5','mono_f010'),('U4','weak_f030_e025'),('L5','dispersion_split_d000'),('M5','dispersion_split_d025'),('H5','dispersion_split_d040'),('U6','mono_weak_uniform6C'),('H7','mono_weak_split7C')]
COMPS={s['name']:s for s in json.loads((ROOT/'selected.json').read_text())}
ROWS={n:[json.loads(f.read_text()) for f in sorted((ROOT/'md'/n).glob('replica_*/replica_result.json'))] for _,n in ORDER}
assert all(len(v)==3 for v in ROWS.values())

def save_table(name,caption,label,columns,header,rows):
    content=['% Generated by generate_component_study_assets.py; do not edit numbers by hand.',r'\begin{table*}[t]',r'\centering',r'\caption{'+caption+'}',r'\label{'+label+'}',r'\small',r'\resizebox{\ifdim\width>\textwidth\textwidth\else\width\fi}{!}{%',r'\begin{tabular}{'+columns+'}',r'\toprule',header+r' \\',r'\midrule']
    content += [' & '.join(row)+r' \\' for row in rows]
    content += [r'\bottomrule',r'\end{tabular}}',r'\end{table*}','']
    (DOC/name).write_text('\n'.join(content))

comp=[]
for code,n in ORDER:
    c=COMPS[n]; neutral=[s for s in c['species'] if s['q']==0];normal=neutral[0]['x']; weak=neutral[1:]
    comp.append([code,f"{c['n_components']}/{c['mechanically_distinct_components']}",f"{normal:.2f}",'+'.join(f"{s['x']:.2f}" for s in weak) if weak else '---',', '.join(f"{s['eps']:g}" for s in weak) if weak else '---','0.05' if c['I']>.13 else '0',f"{c['I']:.2f}"])
save_table('component_study_compositions.tex',r'Selected replicated MD systems. Every mixture contains $x_{+2}=x_{-2}=0.03$ and has unit masses and nominal diameters. The primary neutral solvent and all ions have $\varepsilon=1$. Fractions of secondary neutral solvents and their respective $\varepsilon$ values are listed in matching order; $x_{\pm1}$ is the fraction of each monovalent sign. Label count and mechanically distinct species count are separated. $I=\frac12\sum_i x_iq_i^2$.', 'tab:new_compositions','lcccccc',r'State & Labels/distinct & $x_{\varepsilon=1,\,q=0}$ & Secondary fractions & Secondary $\varepsilon$ & $x_{\pm1}$ & $I$',comp)

states=[]
for code,n in ORDER:
    s=S['systems'][n];r=ROWS[n]
    states.append([code,f"{r[0]['HNC_s_ex']:.5f}",f"{s['s_ex']['mean']:.5f}",f"{s['D_net']['mean']:.5f}",f"{s['D_probe']['mean']:.5f}",f"{np.mean([x['transport']['D_species']['probe_plus2'] for x in r]):.5f}",f"{np.mean([x['transport']['D_species']['probe_minus2'] for x in r]):.5f}"])
save_table('component_study_states.tex',r'Dense-state HNC excess entropy and replicated MD means at $T^*=2$, $\rho^*=0.7$, $N=4000$. Diffusion coefficients are in $\sigma^2/\tau$; $D_{\rm probe}=(D_{+2}+D_{-2})/2$. MD uses the primary 20--100$\tau$ MSD fitting window. L5 is an exact mechanical duplicate of U4 and is excluded from entropy-scaling fits. Confidence intervals for the primary comparisons are reported in Table~\ref{tab:new_contrasts}; absolute-state intervals are in Table~\ref{tab:new_intervals}.','tab:new_states','lrrrrrr',r'State & HNC $s_{\rm ex}/k_B$ & MD $s_{\rm ex}/k_B$ & $D_{\rm net}$ & $D_{\rm probe}$ & $D_{+2}$ & $D_{-2}$',states)

def fmt(v,d=2):return f"${v['mean']:+.{d}f}\\;[{v['CI'][0]:+.{d}f},{v['CI'][1]:+.{d}f}]$"
def pct(v):return fmt(dict(mean=100*np.expm1(v['mean']),CI=100*np.expm1(v['CI'])))
contrasts=[]
for key,label in [('label_null','L5/U4'),('moderate_split','M5/U4'),('high_split','H5/U4'),('high_vs_baseline','H5/B3'),('mono_high_split','H7/U6'),('mono_high_vs_baseline','H7/B5'),('salt_addition_baseline','B5/B3')]:
    a=S['contrasts'][key];contrasts.append([label,fmt(a['delta_s_ex'],5),pct(a['delta_log_D_net']),pct(a['delta_log_D_probe'])])
save_table('component_study_contrasts.tex',r'Paired composition changes, numerator relative to denominator. Brackets are nominal 95\% Student-$t$ intervals from three independent replica pairs (two degrees of freedom), without multiple-comparison correction. Diffusion changes are $100[\exp(\overline{\ln(D_a/D_b)})-1]$ and intervals are transformed in the same way. Entropy differences are per particle in $k_B$. Intervals quantify replica sampling, excluding estimator and finite-size bias.','tab:new_contrasts','lrrr',r'Comparison & $\Delta s_{\rm ex}/k_B$ [95\% CI] & $\Delta D_{\rm net}$ (\%) [95\% CI] & $\Delta D_{\rm probe}$ (\%) [95\% CI]',contrasts)
intervals=[]
for code,n in ORDER:
    intervals.append([code]+[f"$[{S['systems'][n][k]['CI'][0]:.5f},{S['systems'][n][k]['CI'][1]:.5f}]$" for k in ['s_ex','D_net','D_probe']])
save_table('component_study_intervals.tex',r'Absolute-state nominal 95\% Student-$t$ intervals across three independent replicas. Because the states are paired by replica, interval overlap here is not a test of the paired differences in Table~\ref{tab:new_contrasts}. These intervals exclude systematic uncertainty.','tab:new_intervals','lrrr',r'State & $s_{\rm ex}/k_B$ & $D_{\rm net}$ & $D_{\rm probe}$',intervals)
windows=[]
for label,v in G['window_contrasts'].items():windows.append([label]+[pct(v[w]) for w in ['10_50','20_100','50_200']])
save_table('component_study_windows.tex',r'Sensitivity of the paired divalent-ion diffusion change (percent) to MSD fitting window, with nominal 95\% replica intervals. The 20--100$\tau$ window is primary. The positive controlled effect is not uniformly significant across estimators/windows.','tab:new_windows','lrrr',r'Comparison & 10--50$\tau$ & 20--100$\tau$ & 50--200$\tau$',windows)

plt.rcParams.update({'font.size':10,'axes.labelsize':11,'pdf.fonttype':42})
fig,axs=plt.subplots(1,2,figsize=(10,4),layout='constrained')
factor=.7**(1/3)/np.sqrt(2)
for ax,key,title in zip(axs,['D_net','D_probe'],['Mean self-diffusion','Divalent-ion self-diffusion']):
    for code,n in ORDER:
        if code=='L5':continue
        s=S['systems'][n];x=s['s_ex']['mean'];y=s[key]['mean']*factor;xe=np.diff(s['s_ex']['CI'])[0]/2;ye=np.diff(s[key]['CI'])[0]*factor/2
        color='#b2182b' if code in ['B5','U6','H7'] else '#2166ac'
        ax.errorbar(x,y,xerr=xe,yerr=ye,fmt='s' if code in ['B5','U6','H7'] else 'o',color=color,capsize=3)
        xy=(-25,-12) if code=='B5' else (5,-13 if code in ['U6','H7'] else 5)
        ax.annotate(code,(x,y),xytext=xy,textcoords='offset points',fontsize=9)
    ax.set(xlabel=r'$s_{\rm ex}/k_B$',ylabel=r'$D^R=D\rho^{1/3}/\sqrt{T}$',title=title)
    ax.set_yscale('log');ax.margins(x=.12,y=.12);ax.grid(alpha=.2)
for ext in ['pdf','png']:fig.savefig(OUT/f'component_entropy_diffusion.{ext}',dpi=220)
plt.close(fig)

fig,ax=plt.subplots(figsize=(6.5,3.5),layout='constrained')
for group,color,offset in [('H5/U4','#2166ac',.12),('H7/U6','#b2182b',-.12)]:
    vals=[G['window_contrasts'][group][w] for w in ['10_50','20_100','50_200']]
    y=100*np.expm1([v['mean'] for v in vals]);lo=100*np.expm1([v['CI'][0] for v in vals]);hi=100*np.expm1([v['CI'][1] for v in vals]);x=np.arange(3)+offset
    ax.errorbar(x,y,yerr=[y-lo,hi-y],fmt='o',capsize=4,color=color,label=group)
ax.axhline(0,color='black',lw=.8);ax.set_xticks(range(3),['10–50','20–100 (primary)','50–200']);ax.set(xlabel=r'MSD fitting window ($\tau$)',ylabel='Divalent-ion diffusion change (%)');ax.grid(axis='y',alpha=.2);ax.legend(frameon=False)
for ext in ['pdf','png']:fig.savefig(OUT/f'component_window_sensitivity.{ext}',dpi=220)
plt.close(fig)
# The rehabilitation table/figure are generated from the completed follow-up.
R=json.loads((ROOT/'two_pt_rehabilitation/summary.json').read_text())
assert R['complete'] and R['completed_replicas']==24
rrows=[]
for key in ['controlled','mono_controlled']:
    c=R['contrasts'][key]
    for method,model in [('tau10_d1',r'$\delta=1$'),('tau10_d1.5',r'$\delta=1.5$')]:
        v=c['methods'][method]
        rrows.append([c['label'],model,f"{c['TI']['mean']:.5f}",f"{v['delta']['mean']:.5f}",fmt(v['bias_vs_TI'],5)])
save_table('component_study_2pt_contrasts.tex',r'Controlled excess-entropy increments from TI and corrected classical revised 2PT. All entropy quantities are per particle in $k_B$. Bias is the paired difference between the 2PT and TI increments; brackets are nominal 95\% Student-$t$ intervals from three independent replica pairs (two degrees of freedom), without multiplicity correction. The primary partition is $\delta=1$; $\delta=1.5$ is an unfitted sensitivity.', 'tab:2pt_contrasts','llrrr',r'Comparison & Partition & TI $\Delta s_{\rm ex}/k_B$ & 2PT $\Delta s_{\rm ex}/k_B$ & Bias [95\% CI]',rrows)

# Independent all-species pair-entropy analysis, based on trajectories rather than HNC RDFs.
pstates=[]
for code,_ in ORDER:
    d=P['systems'][code]
    pstates.append([code,f"{d['TI_s_ex']['mean']:.4f}",f"{d['s2_resolved']['mean']:.4f}",
                    f"{100*d['pair_fraction_resolved']['mean']:.1f}"+r"\%",f"{d['remainder_resolved']['mean']:.4f}"])
save_table('component_study_pair_entropy_states.tex',r'Full MD thermodynamic-integration excess entropy and directly calculated all-species pair entropy at $T^*=2$, $\rho^*=0.7$. Pair entropy uses the fine-core resolved RDF and is compared with TI state by state. The fraction is the ratio of state means and is descriptive. The residual is $s_{\rm ex}^{\rm TI}-s_2^{\rm MD}$; it contains higher-order correlations and estimator differences.', 'tab:pair_entropy_states','lrrrr',r'State & TI $s_{\rm ex}/k_B$ & MD $s_2/k_B$ & $s_2/s_{\rm ex}$ & Residual $(s_{\rm ex}-s_2)/k_B$',pstates)
pcontrasts=[]
for key,label in [('label_null','L5/U4'),('moderate_split','M5/U4'),('high_split','H5/U4'),('mono_high_split','H7/U6'),('high_vs_baseline','H5/B3'),('mono_high_vs_baseline','H7/B5'),('salt_addition','B5/B3')]:
    d=P['contrasts'][key]
    pcontrasts.append([label,fmt(d['delta_TI'],5),fmt(d['delta_s2_resolved'],5),
                       fmt(d['delta_remainder_resolved'],5),
                       f"{100*np.expm1(d['delta_log_D_plus']['mean']):+.1f}"+r"\%",
                       f"{100*np.expm1(d['delta_log_D_minus']['mean']):+.1f}"+r"\%"])
save_table('component_study_pair_entropy_contrasts.tex',r'Paired differences in full TI excess entropy, MD pair entropy, beyond-pair residual, and the individual probe diffusivities. Entropies are per particle in $k_B$. Diffusion entries are point percent changes from paired log ratios; their nominal 95\% intervals are discussed in the text. The identical-label split is an exact mechanical null.', 'tab:pair_entropy_contrasts','lrrrrr',r'Comparison & $\Delta s_{\rm ex}^{\rm TI}/k_B$ [95\% CI] & $\Delta s_2^{\rm MD}/k_B$ [95\% CI] & $\Delta(s_{\rm ex}-s_2)/k_B$ [95\% CI] & $\Delta D_{+2}$ & $\Delta D_{-2}$',pcontrasts)
source_fig=DOC.parent/'MDPairEntropyAssessment'/'results'/'entropy_benchmark.pdf'
shutil.copy2(source_fig,OUT/'component_pair_entropy_benchmark.pdf')
shutil.copy2(DOC.parent/'MDPairEntropyAssessment'/'results'/'pair_entropy_species_diffusion.pdf',OUT/'component_pair_entropy_species_diffusion.pdf')
for ext in ['pdf','png']:
    shutil.copy2(ROOT/f'two_pt_rehabilitation/entropy_validation.{ext}',OUT/f'component_2pt_validation.{ext}')
delta_fit_file=ROOT/'two_pt_rehabilitation/delta_fit.json'
if delta_fit_file.exists():
    dfit=json.loads(delta_fit_file.read_text())
    drows=[]
    for label in ['M5/U4','H5/U4','H7/U6','H5/B3','H7/B5','B5/B3']:
        comparison=dfit['increments'][label]
        quarter=comparison['methods']['1.25']
        fitted=comparison['methods']['fitted']
        drows.append([label,f"{comparison['TI']['mean']:+.5f}",
                      f"{quarter['delta']['mean']:+.5f}",fmt(quarter['bias'],5),
                      f"{fitted['delta']['mean']:+.5f}",fmt(fitted['bias'],5)])
    global_fit=dfit['global_fit']
    interval=global_fit['replica_index_fits']['CI']
    metrics=dfit['metrics']
    caption=(r'Post-hoc global revised-2PT partition-exponent calibration. '
             r'Paired excess-entropy increments are in $k_B$ per particle; bias is 2PT minus TI, '
             r'with nominal 95\% Student-$t$ intervals across three replica pairs. '
             f"The seven-state unweighted fit gives $\\delta^*={global_fit['delta_star']:.5f}$; "
             f"replica-index 95\\% interval [{interval[0]:.5f},{interval[1]:.5f}]. "
             f"RMS absolute-state bias is {metrics['1.0']['RMS_absolute_state_bias']:.5f}, "
             f"{metrics['1.25']['RMS_absolute_state_bias']:.5f}, and "
             f"{metrics['fitted']['RMS_absolute_state_bias']:.5f} for $\\delta=1$, "
             r'$\delta=1.25$, and fitted $\delta^*$, respectively. '
             r'This calibration was not prespecified and uses the same TI states shown here.')
    save_table('component_study_2pt_delta_fit.tex',caption,'tab:2pt_delta_fit','lrrrrr',
               r'Comparison & TI $\Delta s_{\rm ex}$ & 2PT $\delta=1.25$ & Bias [95\% CI] & 2PT $\delta^*$ & Bias [95\% CI]',drows)
    for ext in ['pdf','png']:
        shutil.copy2(ROOT/f'two_pt_rehabilitation/entropy_validation_delta_fit.{ext}',
                     OUT/f'component_2pt_validation_delta_fit.{ext}')
print('Generated pair-entropy tables and figure alongside the existing manuscript assets.')
